"""Each skill that renders with `_ui.py` carries a byte-identical copy of the plugin-root one.

Skill scripts run by path and cannot import across directories, and on some surfaces the plugin-root
`scripts/` is not mounted at all, so a page that loaded the shared module from there would fail to
render. Pages move onto the module one skill at a time: `ADOPTERS` lists the skills that have, and a
skill whose page renders with the module without being listed is caught too.
"""

from __future__ import annotations

from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
CANONICAL = REPO_ROOT / "founder-skills" / "scripts" / "_ui.py"
SKILLS = REPO_ROOT / "founder-skills" / "skills"
ADOPTERS = ("financial-model-review", "deck-review", "market-sizing", "ic-sim", "cap-table", "competitive-positioning")


def test_the_canonical_module_exists() -> None:
    assert CANONICAL.is_file()


@pytest.mark.parametrize("skill", ADOPTERS)
def test_each_adopter_copy_equals_the_canonical_module(skill: str) -> None:
    copy = SKILLS / skill / "scripts" / "_ui.py"
    assert copy.is_file(), f"{skill} renders with _ui but carries no copy"
    assert copy.read_bytes() == CANONICAL.read_bytes(), f"{copy} drifted; copy the plugin-root file over it"


def test_every_copy_is_an_adopter_and_every_importer_has_a_copy() -> None:
    copies = sorted(p.parent.parent.name for p in SKILLS.glob("*/scripts/_ui.py"))
    assert copies == sorted(ADOPTERS)
    importers = sorted(
        {
            p.parent.parent.name
            for p in SKILLS.glob("*/scripts/*.py")
            if p.name != "_ui.py" and "import _ui" in p.read_text(encoding="utf-8")
        }
    )
    assert set(importers) <= set(ADOPTERS), f"importing _ui without a copy: {sorted(set(importers) - set(ADOPTERS))}"


# Pages that render `_ui.footer()` without the shell's stylesheet carry a copy of the footer's rules, `FOOTER_CSS`.
FOOTER_CSS_COPIES = (
    ("cap-table", "explore.py"),
    ("competitive-positioning", "explore.py"),
)


@pytest.mark.parametrize(("skill", "script"), FOOTER_CSS_COPIES)
def test_every_copied_footer_css_is_the_shells(skill: str, script: str) -> None:
    import re

    shell_css = CANONICAL.read_text(encoding="utf-8").split('UI_CSS = """\\\n', 1)[1].split('"""', 1)[0]
    rules = re.findall(r"^\.ui-footer[^{]*\{.*?\}", shell_css, flags=re.M | re.S)
    assert len(rules) == 5, rules
    src = (SKILLS / skill / "scripts" / script).read_text(encoding="utf-8")
    copy = src.split('FOOTER_CSS = """\\\n', 1)[1].split('"""', 1)[0]
    for rule in rules:
        assert rule in copy, (skill, script, rule)
    assert '_ui.footer("' in src and "FOOTER_CREDIT_HTML" not in src


@pytest.mark.parametrize(("skill", "script"), FOOTER_CSS_COPIES)
def test_those_pages_render_one_shared_footer_and_no_other_credit(skill: str, script: str) -> None:
    import subprocess
    import sys
    import tempfile

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from compose_invocations import drive_compose
    from no_ledger_goldens import FIXTURES, html_argv

    with tempfile.TemporaryDirectory() as td:
        work = Path(td)
        drive_compose(skill, FIXTURES / skill, work)
        out = work / "page.html"
        proc = subprocess.run([sys.executable, *html_argv(skill, script, work, out)], capture_output=True, text=True)
        assert proc.returncode == 0, proc.stderr
        html = out.read_text(encoding="utf-8")
    assert html.count('<footer class="ui-footer">') == 1
    assert "Generated by" not in html and html.count("lool ventures</a>") == 1


@pytest.mark.parametrize(("skill", "script"), FOOTER_CSS_COPIES)
def test_every_copied_footer_variable_is_the_shells(skill: str, script: str) -> None:
    """The copy scopes the variables the footer's rules read to `.ui-footer`; each must equal `_ui.UI_CSS`'s
    `:root` value, or a token change in the shell leaves these footers stale."""
    import re

    shell_css = CANONICAL.read_text(encoding="utf-8").split('UI_CSS = """\\\n', 1)[1].split('"""', 1)[0]
    root = shell_css.split(":root {", 1)[1].split("}", 1)[0]
    shell_vars = dict(re.findall(r"(--[\w-]+):\s*([^;]+);", root))
    src = (SKILLS / skill / "scripts" / script).read_text(encoding="utf-8")
    copy = src.split('FOOTER_CSS = """\\\n', 1)[1].split('"""', 1)[0]
    scoped = copy.split(".ui-footer {", 1)[1].split("}", 1)[0]
    copied = dict(re.findall(r"(--[\w-]+):\s*([^;]+);", scoped))
    assert copied, "no scoped variables found in the copy"
    for name, value in copied.items():
        assert shell_vars.get(name) == value.strip(), (skill, script, name, value, shell_vars.get(name))
